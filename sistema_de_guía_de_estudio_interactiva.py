def cargar_banco_preguntas(ruta_csv):
    """Lee tu archivo CSV adaptándose exactamente a tus columnas."""
    banco = []
    try:
        with open(ruta_csv, mode='r', encoding='utf-8') as archivo:
            lector = csv.DictReader(archivo)
            for fila in lector:
                tipo = fila['tipo'].strip().lower()
                enunciado = fila['pregunta'].strip()

                # Cargar opciones 1, 2 y 3
                opciones = {
                    '1': fila['opcion1'].strip(),
                    '2': fila['opcion2'].strip(),
                    '3': fila['opcion3'].strip()
                }
                # Cargar opción 4 si existe
                if fila.get('opcion4') and fila['opcion4'].strip():
                    opciones['4'] = fila['opcion4'].strip()

                # Separar las respuestas correctas por el punto y coma ';' de tu archivo
                correctas = [str(c.strip()) for c in fila['correcta'].split(';') if c.strip()]

                # Instanciar según el tipo de tu archivo
                if tipo == 'multiple':
                    if '4' in opciones: opciones.pop('4', None) # Forzar 3 opciones
                    banco.append(OpcionMultiple(enunciado, opciones, correctas))
                elif tipo == 'seleccion':
                    banco.append(SeleccionMultiple(enunciado, opciones, correctas))

    except FileNotFoundError:
        print(f"\n[ERROR]: No se encontró el archivo '{ruta_csv}' en el panel izquierdo.")
        return None
    return banco


def guardar_resultados_csv(alumno, ruta_resultados):
    """Guarda las calificaciones finales en 'resultados.csv'."""
    calificaciones_intentos = [0.0, 0.0, 0.0]
    for i, intento in enumerate(alumno.intentos):
        calificaciones_intentos[i] = intento.calificacion

    fila = [
        alumno.nombre,
        alumno.materia,
        calificaciones_intentos[0],
        calificaciones_intentos[1],
        calificaciones_intentos[2],
        alumno.mejor_calificacion,
        datetime.now().strftime("%Y-%m-%d")
    ]

    es_nuevo = not os.path.exists(ruta_resultados)
    with open(ruta_resultados, mode='a', newline='', encoding='utf-8') as archivo:
        escritor = csv.writer(archivo)
        if es_nuevo:
            escritor.writerow(["Nombre completo", "Materia", "Intento1", "Intento2", "Intento3", "Calificacion final", "Fecha"])
        escritor.writerow(fila)


