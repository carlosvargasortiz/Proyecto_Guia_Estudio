def ejecutar_examen():
    print("==================================================")
    print("  SISTEMA DE GUÍA DE ESTUDIO INTERACTIVA - SEGUROS ")
    print("==================================================\n")

    ruta_preguntas_csv = "preguntas_seguros_.csv"
    ruta_csv_temporal = "temp_preguntas.csv"
    ruta_resultados = "resultados.csv"

    banco_completo = []
    try:
        # Cargar el archivo CSV en un DataFrame de pandas
        df_csv = pd.read_csv(ruta_preguntas_csv, encoding='latin1') # Added encoding='latin1'
        # Guardar como CSV temporal para que la función existente pueda leerlo
        df_csv.to_csv(ruta_csv_temporal, index=False, encoding='utf-8')

        # Cargar banco de preguntas desde el CSV temporal
        banco_completo = cargar_banco_preguntas(ruta_csv_temporal)
    except FileNotFoundError:
        print(f"\n[ERROR]: No se encontró el archivo '{ruta_preguntas_csv}' en el panel izquierdo.")
        return
    finally:
        # Limpiar el archivo CSV temporal si existe
        if os.path.exists(ruta_csv_temporal):
            os.remove(ruta_csv_temporal)

    if not banco_completo:
        return

    # print(f"¡Éxito! Se cargaron {len(banco_completo)} preguntas de Seguros.\n")

    # Solicitar nombre al usuario
    nombre = input("Ingresa tu nombre completo: ").strip()
    if not nombre:
        nombre = "Invitado"
        print("No se ingresó un nombre, se usará 'Invitado'.")

    materia = "Seguros"
    print(f"Estudiante registrado: {nombre}")
    print(f"Materia: {materia}\n")

    estudiante = Alumno(nombre, materia)

    # Ciclo de los 3 intentos
    for num_intento in range(1, 4):
        print(f"--- INICIANDO INTENTO {num_intento} DE 3 ---")

        # Seleccionar 10 preguntas aleatorias sin repetir en este intento
        preguntas_intento = random.sample(banco_completo, 10)
        puntaje_acumulado = 0.0

        for i, pregunta in enumerate(preguntas_intento, start=1):
            print(f"\nPregunta {i}: {pregunta.enunciado}")
            for clave, texto in pregunta.opciones.items():
                print(f"  {clave}) {texto}")

            while True:
                entrada_usuario = input("Tu respuesta: ")

                respuestas_usuario = []
                if entrada_usuario:
                    for parte in entrada_usuario.split(','):
                        parte_limpia = str(parte.strip())
                        if parte_limpia:
                            respuestas_usuario.append(parte_limpia)

                # Verificar que todas las respuestas existan en las opciones
                if all(r in pregunta.opciones for r in respuestas_usuario):
                    break
                else:
                    print("¡Opción no válida! Intenta nuevamente.")

            # Evaluar y sumar puntaje
            puntos = pregunta.evaluar(respuestas_usuario)
            puntaje_acumulado += puntos
            print(f"-> Puntos en esta pregunta: {puntos}")

        # Guardar intento terminado
        estudiante.agregar_intento(puntaje_acumulado)
        print(f"\n>>> Fin del Intento {num_intento}. Calificación obtenida: {puntaje_acumulado} / 10.0 <<<\n")

        if num_intento < 3:
          while True:
              otra_vez = input("¿Quieres hacer otro intento? (Si/No): ").strip().upper()

              if otra_vez == "NO":
                  break
              elif otra_vez == "SI":
                  # Sale del while y continúa con el siguiente intento
                  break
              else:
                  print("¡Respuesta no válida!\n")

          if otra_vez == "NO":
              break

        else:
            print("Has completado tus 3 intentos permitidos.")

    # Guardar reporte histórico en el CSV externo
    guardar_resultados_csv(estudiante, ruta_resultados)

    print("\n==================================================")
    print("                REPORTE FINAL                     ")
    print("==================================================")
    print(f"Nombre:           {estudiante.nombre}")
    print(f"Materia:          {estudiante.materia}")
    print(f"Intentos hechos:  {len(estudiante.intentos)}")
    for intento in estudiante.intentos:
        print(f"  - Calificación Intento {intento.numero}: {intento.calificacion}")
    print(f"Calificación Final (Mejor Intento): {estudiante.mejor_calificacion}")
    print("==================================================")
    # print("¡Resultados guardados con éxito en 'resultados.csv'!")

# Arrancar el programa
ejecutar_examen()

"""Este segundo script generara el reporte estadistico"""

def generar_reporte_estadistico(ruta_csv="resultados.csv"):
    """
    Lee el archivo de resultados CSV y calcula las estadísticas requeridas
    por la rúbrica del proyecto final.
    """
    print("=" * 50)
    print("        SISTEMA DE REPORTES ESTADÍSTICOS        ")
    print("=" * 50)

    if not os.path.exists(ruta_csv):
        print(f"⚠️ Error: El archivo '{ruta_csv}' no existe todavía.")
        print("Asegúrate de que al menos un alumno haya terminado el examen para generar datos.")
        return

    total_estudiantes = 0
    suma_calificaciones_finales = 0.0

    calificaciones_por_materia = {}
    calificaciones_por_fecha = {}

    mejor_estudiante = ""
    mejor_calificacion = -1.0

    try:
        with open(ruta_csv, mode='r', encoding='utf-8') as archivo:
            lector = csv.DictReader(archivo)

            for fila in lector:
                total_estudiantes += 1

                nombre = fila["Nombre completo"]
                materia = fila["Materia"]
                fecha = fila["Fecha"].split()[0]
                calif_final = float(fila["Calificacion final"])

                suma_calificaciones_finales += calif_final

                if materia not in calificaciones_por_materia:
                    calificaciones_por_materia[materia] = []
                calificaciones_por_materia[materia].append(calif_final)

                if fecha not in calificaciones_por_fecha:
                    calificaciones_por_fecha[fecha] = []
                calificaciones_por_fecha[fecha].append(calif_final)

                if calif_final > mejor_calificacion:
                    mejor_calificacion = calif_final
                    mejor_estudiante = nombre

        if total_estudiantes == 0:
            print("🛑 El archivo CSV está vacío. No hay alumnos registrados.")
            return

        # Define promedio_general before its usage
        promedio_general = suma_calificaciones_finales / total_estudiantes

        print(f"✔️ Número total de estudiantes evaluados: {total_estudiantes}")
        print(f"✔️ Promedio general de calificaciones: {promedio_general:.2f} / 10.0")

        print("\n📊 Promedio por Materia:")
        for mat, lista_califs in calificaciones_por_materia.items():
            prom_mat = sum(lista_califs) / len(lista_califs)
            print(f"   - {mat}: {prom_mat:.2f}")

        print("\n📅 Promedio por Fecha de Evaluación:")
        for fec, lista_califs in calificaciones_por_fecha.items():
            prom_fec = sum(lista_califs) / len(lista_califs)
            print(f"   - {fec}: {prom_fec:.2f}")

        print("\n🏆 Rendimiento Destacado:")
        print(f"   - Mejor estudiante: {mejor_estudiante} (Calificación: {mejor_calificacion:.2f})")
        print("=" * 50)

    except KeyError as e:
        print(f"❌ Error de formato en el CSV: Falta la columna {e}.")
    except ValueError:
        print("❌ Error: Se encontraron datos numéricos corruptos en las calificaciones.")
    except Exception as e:
        print(f"❌ Ocurrió un error inesperado al procesar el reporte: {e}")

if __name__ == "__main__":
    generar_reporte_estadistico()