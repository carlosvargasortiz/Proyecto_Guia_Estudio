# 1. CLASES EN ORIENTACIÓN A OBJETOS (POO)
# ==================
class Pregunta(ABC):
    """Clase abstracta obligatoria para la estructura de una pregunta."""
    def __init__(self, enunciado, opciones, correctas):
        self.enunciado = enunciado
        self.opciones = opciones
        self.correctas = correctas  # Lista de strings limpios (ej: ['1'] o ['1', '2'])

    @abstractmethod
    def evaluar(self, respuestas_usuario):
        """Método abstracto que heredarán las clases hijas."""
        pass


class OpcionMultiple(Pregunta):
    """Pregunta tipo 'multiple': 3 opciones, 1 correcta (1 pt o 0 pts)."""
    def evaluar(self, respuestas_usuario):
        # Si responde exactamente la única opción correcta
        if len(respuestas_usuario) == 1 and respuestas_usuario[0] in self.correctas:
            return 1.0
        return 0.0


class SeleccionMultiple(Pregunta):
    """Pregunta tipo 'seleccion': 4 opciones, 2 correctas (1, 0.5 o 0 pts)."""
    def evaluar(self, respuestas_usuario):
        # Si selecciona 0 opciones o más de 2 -> 0 puntos automáticamente
        if len(respuestas_usuario) == 0 or len(respuestas_usuario) >= 3:
            return 0.0

        # Contar aciertos y errores
        correctas_elegidas = sum(1 for r in respuestas_usuario if r in self.correctas)
        incorrectas_elegidas = len(respuestas_usuario) - correctas_elegidas

        # Si seleccionó aunque sea una opción incorrecta -> 0 puntos totales
        if incorrectas_elegidas > 0:
            return 0.0

        # Si seleccionó las 2 correctas -> 1 punto completo
        if correctas_elegidas == 2:
            return 1.0
        # Si seleccionó solo una correcta y ninguna incorrecta -> 0.5 puntos
        elif correctas_elegidas == 1:
            return 0.5

        return 0.0


class Intento:
    """Guarda el número de intento y su calificación."""
    def __init__(self, numero, calificacion):
        self.numero = numero
        self.calificacion = calificacion


class Alumno:
    """Clase que representa al alumno y sus intentos (Composición)."""
    def __init__(self, nombre, materia):
        self.nombre = nombre
        self.materia = materia
        self.intentos = []

    def agregar_intento(self, calificacion):
        if len(self.intentos) < 3:
            num_intento = len(self.intentos) + 1
            self.intentos.append(Intento(num_intento, calificacion))
        else:
            raise ValueError("Ya se realizaron los 3 intentos máximos.")

    @property
    def mejor_calificacion(self):
        if not self.intentos:
            return 0.0
        return max(intento.calificacion for intento in self.intentos)


